#!/usr/bin/env python3
"""Toy benchmark for layer A (no hardware): grip-force baselines vs shear-margin control.

Writes
  docs/figures/lr1_toy_benchmark.png   4-panel figure
  results/toy_benchmark.md             metric tables

Usage:  python scripts/run_toy_benchmark.py [--n 500] [--seed 1]
All numbers are synthetic: the simulator encodes our assumptions and exists to
build the evaluation harness (metrics, baselines, latency budget) before hardware time.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from shear_agent.sim import (  # noqa: E402
    ShearMargin,
    SimConfig,
    SlipReactive,
    default_controllers,
    sample_conditions,
    simulate,
)
from shear_agent.sim.toy_grasp import tangential_load  # noqa: E402

COLORS = {
    "Fixed 15 N": "#94A3B8",
    "Fixed 60 N": "#475569",
    "Slip-reactive": "#F59E0B",
    "Shear-margin (ours)": "#0D9488",
}
LATENCIES = [0.0, 0.025, 0.05, 0.1, 0.15, 0.2]
EXAMPLE = dict(mass=0.8, mu=0.4, resist_peak=8.0)


def run(n: int, seed: int):
    mass, mu, resist = sample_conditions(n, seed=seed)
    mc = [simulate(c, mass, mu, resist, seed=seed + 1) for c in default_controllers()]
    ex = [simulate(c, seed=seed + 2, record=True, **EXAMPLE) for c in default_controllers()]
    sweep = {}
    for make in (SlipReactive, ShearMargin):
        rows = []
        for lat in LATENCIES:
            res = simulate(make(), mass, mu, resist, cfg=SimConfig(sense_latency=lat), seed=seed + 1)
            rows.append(dict(res.summary(), latency_ms=1e3 * lat))
        sweep[make.name] = rows
    return mc, ex, sweep


def write_table(mc, sweep, n: int, seed: int) -> str:
    cfg = SimConfig()
    lines = [
        "# Toy benchmark (layer A): synthetic, not hardware results",
        "",
        f"Generated by `python scripts/run_toy_benchmark.py --n {n} --seed {seed}`. "
        f"{n} random books (mass 0.2-1.2 kg, skin-cover friction 0.3-0.9, neighbour resistance 0-10 N); "
        f"ultrasound frames every {1e3 * cfg.sense_period:.0f} ms with {1e3 * cfg.sense_latency:.0f} ms latency; "
        f"gripper force {cfg.f_min:.0f}-{cfg.f_max:.0f} N with {1e3 * cfg.grip_tau:.0f} ms lag; "
        f"a pull fails when the fingers slide {1e3 * cfg.drop_slip:.0f} mm along the book.",
        "",
        "| controller | failed pulls | mean slip (mm) | pulls with slip > 1 mm | mean grip (N) | peak grip (N) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in mc:
        s = r.summary()
        lines.append(
            f"| {r.name} | {100 * s['drop_rate']:.1f} % | {s['slip_mm']:.2f} | "
            f"{100 * np.mean(r.slip_mm > 1.0):.0f} % | {s['mean_grip_N']:.1f} | {s['peak_grip_N']:.1f} |"
        )
    names = list(sweep)
    lines += [
        "",
        "Latency sweep (same books): mean slip in mm (failed pulls in %).",
        "",
        "| sensing latency (ms) | " + " | ".join(names) + " |",
        "|---:|" + "---:|" * len(names),
    ]
    for i, lat in enumerate(LATENCIES):
        cells = [f"{sweep[nm][i]['slip_mm']:.2f} ({100 * sweep[nm][i]['drop_rate']:.1f} %)" for nm in names]
        lines.append(f"| {1e3 * lat:.0f} | " + " | ".join(cells) + " |")
    text = "\n".join(lines) + "\n"
    out = ROOT / "results" / "toy_benchmark.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return text


def plot(mc, ex, sweep, n: int) -> Path:
    plt.rcParams.update({
        "font.family": ["Lato", "DejaVu Sans"],
        "font.size": 10,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.titleweight": "bold",
        "axes.titlesize": 11,
    })
    fig, axs = plt.subplots(2, 2, figsize=(11, 7.4), constrained_layout=True)
    t = ex[0].trace["t"]

    ax = axs[0, 0]
    need = 0.5 * tangential_load(t, EXAMPLE["mass"], EXAMPLE["resist_peak"]) / EXAMPLE["mu"]
    ax.plot(t, need, color="k", ls="--", lw=1.4, label="grip needed to hold (shear load / μ)")
    for r in ex:
        ax.plot(t, r.trace["f_n"], color=COLORS[r.name], lw=2, label=r.name)
    ax.set(xlabel="time (s)", ylabel="force (N)", ylim=(0, 70),
           title=f"(a) One pull: {EXAMPLE['mass']} kg book, μ = {EXAMPLE['mu']}, "
                 f"{EXAMPLE['resist_peak']:.0f} N neighbour drag")
    ax.legend(frameon=False, fontsize=9, loc="upper right")

    ax = axs[0, 1]
    for r in ex:
        ax.plot(t, r.trace["slip_mm"], color=COLORS[r.name], lw=2, label=r.name)
    drop = 1e3 * SimConfig().drop_slip
    ax.axhline(drop, color="#EF4444", ls=":", lw=1.3)
    ax.text(0.02, drop + 0.4, "failed pull (fingers slid off)", color="#EF4444", fontsize=9)
    ax.set(xlabel="time (s)", ylabel="finger-on-book slip (mm)", ylim=(0, drop + 3),
           title="(b) Accumulated slip during the same pull")

    ax = axs[1, 0]
    offsets = {"Slip-reactive": (10, 16), "Shear-margin (ours)": (12, -26)}
    for r in mc:
        s = r.summary()
        x, y = s["mean_grip_N"], 100 * s["drop_rate"]
        ax.scatter(x, y, s=140, color=COLORS[r.name], edgecolor="white", lw=1.5, zorder=3)
        ax.annotate(f"{r.name}: slip {s['slip_mm']:.1f} mm", (x, y), xytext=offsets.get(r.name, (9, 6)),
                    textcoords="offset points", fontsize=9, color="#0F172A",
                    arrowprops=dict(arrowstyle="-", color="#CBD5E1", lw=0.8))
    ax.set(xlabel="mean grip force while holding (N)", ylabel="failed pulls (%)",
           xlim=(0, 80), ylim=(-4, 18), yticks=[0, 5, 10, 15],
           title=f"(c) {n} random books, 50 ms sensing loop")
    ax.annotate("better", xy=(36, 3), xytext=(46, 9), fontsize=9, color="#64748B",
                arrowprops=dict(arrowstyle="->", color="#64748B"))

    ax = axs[1, 1]
    for name, rows in sweep.items():
        ax.plot([r["latency_ms"] for r in rows], [r["slip_mm"] for r in rows], marker="o",
                color=COLORS[name], lw=2, label=name)
    ax.axvline(50, color="#64748B", ls="--", lw=1)
    ax.text(54, 0.3, "today's pipeline\n(~50 ms)", color="#64748B", fontsize=9)
    ax.set(xlabel="sensing latency (ms)", ylabel="mean slip per pull (mm)", ylim=(0, None),
           title="(d) What the sensing latency costs")
    ax.legend(frameon=False, fontsize=9, loc="upper left")

    fig.suptitle("Toy 1-D simulation: synthetic numbers that set up the evaluation harness, not hardware results",
                 fontsize=10, color="#64748B")
    out = ROOT / "docs" / "figures" / "lr1_toy_benchmark.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=160)
    plt.close(fig)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description="Toy benchmark for layer A (synthetic).")
    ap.add_argument("--n", type=int, default=500, help="number of random books")
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    mc, ex, sweep = run(args.n, args.seed)
    print(write_table(mc, sweep, args.n, args.seed))
    print("figure:", plot(mc, ex, sweep, args.n).relative_to(ROOT))


if __name__ == "__main__":
    main()
